const LABEL_SIZE = 16

export function textWidth(text: string, bold: boolean): number {
  const table: Record<string, number> = bold ? ADVANCE.bold : ADVANCE.regular
  let em = 0
  for (const ch of text) {
    em += table[ch] ?? 0.6
  }
  return em * LABEL_SIZE
}
